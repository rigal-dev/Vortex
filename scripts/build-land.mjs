#!/usr/bin/env node
/**
 * Regenerates src/land.ts from Natural Earth 110m land polygons (public domain).
 *
 *   npm run land
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'land.ts');
const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';

const res = await fetch(URL);
if (!res.ok) throw new Error(`Download failed: HTTP ${res.status}`);
const gj = await res.json();

const rings = [];
for (const f of gj.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const poly of polys) {
    const exterior = poly[0]; // ignore holes (lakes)
    if (exterior.every(([, lat]) => lat < -60)) continue; // drop Antarctica for a cleaner look
    rings.push(exterior.map(([lon, lat]) => [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10]));
  }
}

const body = rings.map((r) => `  ${JSON.stringify(r)},`).join('\n');
const src = `/** Natural Earth 110m land outlines as [lon, lat] rings. Generated by scripts/build-land.mjs. */
export type Ring = ReadonlyArray<readonly [number, number]>;

export const LAND: ReadonlyArray<Ring> = [
${body}
];
`;
writeFileSync(OUT, src);
console.log(`Wrote ${rings.length} rings to ${OUT}`);
